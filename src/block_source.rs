//! Шов №1: откуда берутся байты диска.
//!
//! Адресация — **логическими секторами (LBA)**, потому что файловые системы
//! (FAT и пр.) оперируют логическими секторами, а не CHS. Отображение LBA→CHS
//! (цилиндр/головка/сектор) и дорожечный кэш — деталь конкретной реализации:
//!
//!   - Шаг 2: `ImageFile` — линейный .img, LBA n = смещение n*bytes в файле.
//!   - Шаг 3: `Greaseweazle` — LBA→CHS через геометрию из BPB, чтение дорожек
//!            в кэш внутри актора.
//!   - Фаза 4: собственный протокол + MFM-декодер (замена только этой реализации).

use std::io;

/// Источник логических секторов носителя (read-only, решение №5).
pub trait BlockSource: Send {
    /// Размер логического сектора в байтах (обычно 512).
    fn block_size(&self) -> usize;

    /// Общее число логических секторов на носителе.
    fn block_count(&self) -> u64;

    /// Прочитать один логический сектор по его LBA-номеру.
    fn read_block(&mut self, lba: u64) -> io::Result<Vec<u8>>;
}
